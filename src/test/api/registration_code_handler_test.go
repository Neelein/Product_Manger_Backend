func setupRegistrationCodeTest() (*database.MemberRepositoryPGX, *database.SessionCache, *mux.Router) {
	memberRepo := database.NewMemberRepositoryPGX(testPool)
	sessionCache := database.NewSessionCache(time.Hour)
	codeRepo := database.NewRegistrationCodeRepositoryPGX(testPool)
	handler := api.NewRegistrationCodeHandler(codeRepo)

	auth := api.AuthMiddleware(sessionCache, memberRepo)
	adminAuth := api.RequireRole("admin", auth)

	r := mux.NewRouter()
	r.Handle("/api/registration-codes", adminAuth(http.HandlerFunc(handler.CreateCode))).Methods("POST")
	r.Handle("/api/registration-codes", adminAuth(http.HandlerFunc(handler.ListCodes))).Methods("GET")
	r.Handle("/api/registration-codes/{id}", adminAuth(http.HandlerFunc(handler.DeleteCode))).Methods("DELETE")

	return memberRepo, sessionCache, r
}

// authCookie creates a member with the given role in the same session cache the
// router uses, and returns their session cookie.
func authCookie(t *testing.T, memberRepo *database.MemberRepositoryPGX, sessionCache *database.SessionCache, role string) *http.Cookie {
	t.Helper()
	member := createAuthMember(t, memberRepo, sessionCache)
	if role == "admin" {
		_, err := testPool.Exec(context.Background(), "UPDATE members SET role = 'admin' WHERE id = $1", member.ID)
		require.NoError(t, err)
	}
	session := domain.Session{MemberID: member.ID}
	require.NoError(t, sessionCache.Create(context.Background(), &session))
	return &http.Cookie{Name: "session_key", Value: session.SessionKey}
}

func doCodeReq(t *testing.T, r *mux.Router, method, path string, body []byte, cookie *http.Cookie) *httptest.ResponseRecorder {
	t.Helper()
	req := httptest.NewRequest(method, path, bytes.NewReader(body))
	req.Header.Set("Content-Type", "application/json")
	if cookie != nil {
		req.AddCookie(cookie)
	}
	w := httptest.NewRecorder()
	r.ServeHTTP(w, req)
	return w
}

func TestRegistrationCode_AdminCreate(t *testing.T) {
	defer cleanupMembers(t)
	memberRepo, sessionCache, r := setupRegistrationCodeTest()
	cookie := authCookie(t, memberRepo, sessionCache, "admin")

	body, _ := json.Marshal(domain.CreateRegistrationCodeRequest{Code: "ADMIN-007"})
	w := doCodeReq(t, r, "POST", "/api/registration-codes", body, cookie)
	assert.Equal(t, http.StatusCreated, w.Code)

	var resp domain.RegistrationCodeResponse
	require.NoError(t, json.NewDecoder(w.Body).Decode(&resp))
	assert.Equal(t, "ADMIN-007", resp.Code.Code)
	assert.Equal(t, "available", resp.Code.Status)
}

