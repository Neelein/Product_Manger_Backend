func TestRegistrationCode_ListAndDelete(t *testing.T) {
	defer cleanupMembers(t)
	memberRepo, sessionCache, r := setupRegistrationCodeTest()
	cookie := authCookie(t, memberRepo, sessionCache, "admin")

	codeRepo := database.NewRegistrationCodeRepositoryPGX(testPool)
	created, err := codeRepo.Create(context.Background(), "", "LIST-001")
	require.NoError(t, err)

	w := doCodeReq(t, r, "GET", "/api/registration-codes", nil, cookie)
	assert.Equal(t, http.StatusOK, w.Code)

	var list domain.RegistrationCodeListResponse
	require.NoError(t, json.NewDecoder(w.Body).Decode(&list))
	require.NotEmpty(t, list.Codes)
	assert.Equal(t, "LIST-001", list.Codes[0].Code)

	w = doCodeReq(t, r, "DELETE", "/api/registration-codes/"+created.ID, nil, cookie)
	assert.Equal(t, http.StatusOK, w.Code)

	var count int
	_ = testPool.QueryRow(context.Background(), "SELECT count(*) FROM registration_codes WHERE id = $1", created.ID).Scan(&count)
	assert.Equal(t, 0, count)
	assert.Equal(t, http.StatusOK, w.Code)
}

